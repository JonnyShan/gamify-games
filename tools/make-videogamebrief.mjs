// Builds videogamebrief/ : a Livewire-only copy of racing/ for https://videogamebrief.com/racing/.
// Livewire is the default (no ?brand=), and nothing Gamify ships: no name, logo, Raceway voice lines,
// gamify.com links, Gamify analytics or Gamify leaderboard. Run from the repo root:  node tools/make-videogamebrief.mjs
// The output is committed and served as-is (Cloudflare Pages, no build step). Re-run after racing/ changes.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SRC = path.join(ROOT, 'racing');
const OUT = path.join(ROOT, 'videogamebrief');
const GAME = path.join(OUT, 'racing');
const URL_ = 'https://videogamebrief.com/racing/';
const PACK = 'livewire';

// Files and folders that are Gamify (or other brands) and must not ship.
const SKIP = [/^brands\/(?!livewire\/)[^/]+/, /^assets\/brand\//, /^assets\/voice\/intro-/];

fs.rmSync(GAME, { recursive: true, force: true });
(function copy(dir) {
  for (const e of fs.readdirSync(path.join(SRC, dir), { withFileTypes: true })) {
    const rel = dir ? `${dir}/${e.name}` : e.name;
    if (SKIP.some((r) => r.test(rel + (e.isDirectory() ? '/' : '')))) continue;
    if (e.isDirectory()) { fs.mkdirSync(path.join(GAME, rel), { recursive: true }); copy(rel); }
    else fs.copyFileSync(path.join(SRC, rel), path.join(GAME, rel));
  }
})('');

// Resolve the Livewire brand exactly as racing/js/brand.js does for ?brand=livewire, then ship only the result.
const brandSrc = fs.readFileSync(path.join(SRC, 'js/brand.js'), 'utf8');
const coreText = brandSrc.match(/const CORE = (\{[\s\S]*?\n\});/)[1];
const CORE = Function(`return (${coreText});`)();
const pack = JSON.parse(fs.readFileSync(path.join(SRC, `brands/${PACK}/brand.json`), 'utf8'));
const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v);
const merge = (a, b) => { const o = { ...a }; for (const k in b) o[k] = isObj(b[k]) && isObj(a[k]) ? merge(a[k], b[k]) : b[k]; return o; };
const dir = `brands/${PACK}/`, name = pack.name, NAME = name.toUpperCase(), accent = pack.accent;
const derived = {
  id: `${PACK}_vgb_f1_v1`, name, wordmark: NAME, circuit: `${name} Raceway`, title: `${name} Grand Prix`,
  description: `${name} GRAND PRIX: a time-attack F1 racing game on the fictional ${name} Raceway.`,
  primaryHot: accent, accent,
  signs: { ...CORE.signs, safetySub: `${NAME} · GRAND PRIX` },
  share: { url: URL_, text: `I just lapped ${name} Raceway in {time}. Beat that: ${URL_}` },
  introLines: false,
  car: { ...CORE.car, accent, ...(pack.dark ? { body: pack.dark } : {}) },
};
const B = merge(merge(CORE, derived), pack);
B.logo = dir + pack.logo;
B.logoUi = dir + (pack.logoUi || pack.logo);
B.product = pack.product ? dir + pack.product : null;
B.repaint = { from: CORE.accent, to: accent };   // the bike/rider paint is authored in the core blue
B.accent2 = accent;                               // core orange is a house colour; use the pack accent
B.leaderboard = null;                             // board stays on each device (no shared Worker on this domain)
fs.writeFileSync(path.join(GAME, 'js/brand.js'),
  `// Livewire Grand Prix: every brand value in this build (generated by tools/make-videogamebrief.mjs).\n` +
  `export const BRAND = ${JSON.stringify(B, null, 2)};\n`);

// Small edits elsewhere: comments that name the house brand, the text fallback, and analytics off.
const edit = (rel, pairs) => {
  const p = path.join(GAME, rel); let s = fs.readFileSync(p, 'utf8');
  for (const [a, b] of pairs) { if (!s.match(a)) throw new Error(`${rel}: no match for ${a}`); s = s.replace(a, b); }
  fs.writeFileSync(p, s);
};
edit('js/audio.js', [[/\/\/ re-recorded for .*$/m, '// circuit intro lines are not used in this build']]);
edit('js/car.js', [[/'GAMIFY'/, `'${NAME}'`]]);
edit('js/config.js', [[/^\/\/ Google Analytics 4 measurement ID.*$/m, '// Analytics measurement ID; \'\' turns analytics off.'], [/ANALYTICS_ID = '[^']*'/, "ANALYTICS_ID = ''"]]);
edit('js/main.js', [[/paint was made in \w+ blue/, 'paint was made in the core blue']]);
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
edit('index.html', [[/<!-- brand:head[\s\S]*?<!-- \/brand:head -->/,
  `<!-- brand:head -->\n<meta name="theme-color" content="${B.dark}">\n<meta name="robots" content="noindex, nofollow">\n` +
  `<title>${esc(B.title)}</title>\n<meta name="description" content="${esc(B.description)}">\n` +
  `<meta property="og:title" content="${esc(B.title)}">\n<meta property="og:description" content="${esc(B.description)}">\n` +
  `<meta property="og:url" content="${URL_}">\n<meta name="twitter:card" content="summary">\n<!-- /brand:head -->`]]);

// Fail the build if anything Gamify is left in the shipped files.
const hits = [];
(function scan(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) scan(p);
    else if (/gamify/i.test(e.name) || /gamify/i.test(fs.readFileSync(p).toString('latin1'))) hits.push(path.relative(OUT, p));
  }
})(OUT);
if (hits.length) { console.error('Gamify found in:\n  ' + hits.join('\n  ')); process.exit(1); }
console.log(`videogamebrief/racing built, ${B.title}, no "gamify" in any shipped file.`);
